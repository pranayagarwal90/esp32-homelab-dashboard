#!/usr/bin/env python3
"""Regenerate the manifest-signature TEST vectors.

TEST ONLY - NOT PRODUCTION RELEASE KEYS. Two throwaway P-256 keys
(homedeck-test-a, homedeck-test-b) are generated in a temporary directory,
used to sign a few manifests, and deleted: only their PUBLIC keys and the
signatures are kept, in
  firmware/test/vectors/manifest_signature_v2.json  (Python and C++ tests)
  firmware/include/ManifestSignatureKat.h           (the device's self-test)
ECDSA signatures are randomized, so each run writes different (equally
valid) vectors; commit the regenerated files together.
"""
import base64
import hashlib
import json
from pathlib import Path
import sys
import tempfile

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "backend"))
sys.path.insert(0, str(ROOT / "tools"))
from firmware_updates import MANIFEST_VERSION, PRODUCT, canonical_payload, validate_manifest  # noqa: E402
import release_signing as rs  # noqa: E402

VECTORS = ROOT / "firmware" / "test" / "vectors" / "manifest_signature_v2.json"
KAT_HEADER = ROOT / "firmware" / "include" / "ManifestSignatureKat.h"
WARNING = "TEST ONLY - NOT A PRODUCTION RELEASE KEY. Throwaway keys; private halves were discarded."

CASES = [
    ("signed-by-a", "homedeck-test-a", "1.0.2", 1069000, "Improved reliability."),
    ("signed-by-b", "homedeck-test-b", "2.0.0", 1048576, "Rotated to the next release key."),
    ("empty-notes", "homedeck-test-a", "1.0.3", 1, ""),
    ("max-notes", "homedeck-test-a", "65535.65535.65535", 4194304,
     ("Edge = cases: size=7:x\\n and key_id=homedeck-test-b " * 4)[:200]),
]


def main():
    keys, vectors = {}, []
    with tempfile.TemporaryDirectory() as directory:
        paths = {}
        for key_id in ("homedeck-test-a", "homedeck-test-b"):
            paths[key_id] = Path(directory) / f"{key_id}.pem"
            rs.generate_private_key(paths[key_id], encrypt=False)
            keys[key_id] = rs.public_key_from_private(paths[key_id])
        for name, key_id, version, size, notes in CASES:
            digest = hashlib.sha256(f"{name} firmware image".encode()).hexdigest()
            filename = f"{PRODUCT}-{version}.bin"
            payload = canonical_payload(MANIFEST_VERSION, PRODUCT, version, filename, size, digest, notes, key_id)
            signature = rs.sign(paths[key_id], payload)
            assert rs.verify(keys[key_id], payload, signature)
            manifest = {"manifest_version": MANIFEST_VERSION, "product": PRODUCT, "version": version,
                        "filename": filename, "size": size, "sha256": digest, "notes": notes,
                        "key_id": key_id, "signature": rs.b64(signature)}
            validate_manifest(manifest)
            vectors.append({"name": name, "manifest": manifest, "payload_hex": payload.hex(),
                            "payload_sha256": hashlib.sha256(payload).hexdigest()})
    # The temporary directory, and both private keys, are gone here.

    VECTORS.parent.mkdir(parents=True, exist_ok=True)
    VECTORS.write_text(json.dumps({"warning": WARNING, "public_keys": {k: v.hex() for k, v in keys.items()},
                                   "vectors": vectors}, indent=2) + "\n")

    kat = vectors[0]["manifest"]
    signature = base64.b64decode(kat["signature"])
    KAT_HEADER.write_text(f"""#pragma once
#include <stdint.h>

// {WARNING}
// Generated by tools/make-signature-test-vectors.py (vector "signed-by-a").
//
// Known-answer test for the device's ECDSA P-256 verifier: before trusting a
// verification result, the firmware checks that this valid signature
// verifies and that a corrupted copy does not. This key is NEVER a trusted
// update key (TrustedUpdateKeys.h); nothing signed with it can be installed.

constexpr const char* KAT_KEY_ID = "{kat['key_id']}";
constexpr const char* KAT_VERSION = "{kat['version']}";
constexpr const char* KAT_FILENAME = "{kat['filename']}";
constexpr uint32_t KAT_SIZE = {kat['size']};
constexpr const char* KAT_SHA256 = "{kat['sha256']}";
constexpr const char* KAT_NOTES = "{kat['notes']}";

{rs.c_array("KAT_PUBLIC_KEY", keys[kat['key_id']])}

{rs.c_array("KAT_SIGNATURE", signature)}
""")
    print(f"Wrote {VECTORS.relative_to(ROOT)} and {KAT_HEADER.relative_to(ROOT)} ({len(vectors)} vectors).")


if __name__ == "__main__":
    main()
